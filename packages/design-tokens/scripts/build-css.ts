// Generates css/tokens.css from src/index.ts so the web app and the tokens never drift.
// Run: npm run tokens
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { colors, radius } from '../src/index';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

function block(palette: Record<string, string>): string {
  return Object.entries(palette)
    .map(([name, value]) => `  --tgs-${kebab(name)}: ${value};`)
    .join('\n');
}

const css = `/* GENERATED by packages/design-tokens/scripts/build-css.ts — do not edit by hand. */
:root {
${block(colors.light)}
  --tgs-radius-sm: ${radius.sm}px;
  --tgs-radius-md: ${radius.md}px;
  --tgs-radius-lg: ${radius.lg}px;
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${block(colors.dark).replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${block(colors.dark)}
  color-scheme: dark;
}
`;

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'css', 'tokens.css');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens.css written → ${out}`);
