// Generates the web outputs from the TS source (run: npm run tokens):
//   css/tokens.css    CSS custom properties (--tgs-*), light + dark
//   css/tailwind.css  Tailwind v4 @theme mapping. Clears Tailwind's default palette so only tokens exist.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brand } from '../src/brand';
import { elevation, motion, radius } from '../src/layout';
import { semanticColors, type SemanticColors } from '../src/semantic';
import { textRoles } from '../src/typography';

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const HEADER = '/* GENERATED by packages/design-tokens/scripts/build-css.ts from src/*.ts. Do not edit. */\n';

function colorVars(c: SemanticColors): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(c.bg)) out.push(`--tgs-bg-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(c.text)) out.push(`--tgs-text-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(c.border)) out.push(`--tgs-border-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(c.brand)) out.push(`--tgs-brand-${kebab(k)}: ${v};`);
  for (const [name, role] of Object.entries(c.status))
    for (const [k, v] of Object.entries(role)) out.push(`--tgs-status-${name}-${k}: ${v};`);
  for (const [k, v] of Object.entries(c.money)) out.push(`--tgs-money-${k}: ${v};`);
  c.chart.forEach((v, i) => out.push(`--tgs-chart-${i + 1}: ${v};`));
  return out;
}

function staticVars(): string[] {
  const out: string[] = [
    `--tgs-font-sans: ${brand.fontFamily.sans};`,
    `--tgs-font-mono: ${brand.fontFamily.mono};`,
  ];
  for (const [k, v] of Object.entries(radius)) out.push(`--tgs-radius-${kebab(k)}: ${v === 9999 ? '9999px' : `${v}px`};`);
  for (const [k, v] of Object.entries(elevation)) out.push(`--tgs-shadow-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(motion.duration)) out.push(`--tgs-duration-${k}: ${v}ms;`);
  for (const [k, v] of Object.entries(motion.easing)) out.push(`--tgs-ease-${k}: ${v};`);
  for (const [k, r] of Object.entries(textRoles)) {
    const n = kebab(k);
    out.push(`--tgs-type-${n}-size: ${r.fontSize}px;`, `--tgs-type-${n}-line-height: ${r.lineHeight}px;`, `--tgs-type-${n}-weight: ${r.fontWeight};`);
  }
  return out;
}

const indent = (lines: string[], n: number) => lines.map((l) => ' '.repeat(n) + l).join('\n');

const tokensCss = `${HEADER}
:root {
${indent([...staticVars(), ...colorVars(semanticColors.light)], 2)}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${indent(colorVars(semanticColors.dark), 4)}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${indent(colorVars(semanticColors.dark), 2)}
  color-scheme: dark;
}
`;

// ---- Tailwind mapping: utilities named by role (bg-surface, text-fg-secondary, border-line, rounded-card…)
const tw: string[] = ['--color-*: initial;', '--color-transparent: transparent;', '--color-current: currentColor;'];
const add = (name: string, v: string) => tw.push(`--color-${name}: var(${v});`);
const c = semanticColors.light;
add('canvas', '--tgs-bg-canvas');
add('surface', '--tgs-bg-surface');
add('surface-subtle', '--tgs-bg-surface-subtle');
add('surface-muted', '--tgs-bg-surface-muted');
add('surface-sunken', '--tgs-bg-surface-sunken');
add('inverse', '--tgs-bg-inverse');
add('overlay', '--tgs-bg-overlay');
add('fg', '--tgs-text-primary');
add('fg-secondary', '--tgs-text-secondary');
add('fg-tertiary', '--tgs-text-tertiary');
add('fg-disabled', '--tgs-text-disabled');
add('fg-inverse', '--tgs-text-inverse');
add('link', '--tgs-text-link');
add('on-brand', '--tgs-text-on-brand');
add('line-subtle', '--tgs-border-subtle');
add('line', '--tgs-border-default');
add('line-strong', '--tgs-border-strong');
add('focus', '--tgs-border-focus');
for (const k of Object.keys(c.brand)) add(k === 'solid' ? 'brand' : `brand-${kebab(k)}`, `--tgs-brand-${kebab(k)}`);
for (const [name, role] of Object.entries(c.status)) for (const k of Object.keys(role)) add(`${name}-${k}`, `--tgs-status-${name}-${k}`);
add('credit', '--tgs-money-credit');
add('debit', '--tgs-money-debit');
c.chart.forEach((_, i) => add(`chart-${i + 1}`, `--tgs-chart-${i + 1}`));

tw.push('--font-sans: var(--tgs-font-sans);', '--font-mono: var(--tgs-font-mono);');
for (const k of Object.keys(radius)) tw.push(`--radius-${kebab(k)}: var(--tgs-radius-${kebab(k)});`);
for (const k of Object.keys(elevation)) tw.push(`--shadow-${kebab(k)}: var(--tgs-shadow-${kebab(k)});`);
for (const k of Object.keys(textRoles)) {
  const n = kebab(k);
  tw.push(
    `--text-${n}: var(--tgs-type-${n}-size);`,
    `--text-${n}--line-height: var(--tgs-type-${n}-line-height);`,
    `--text-${n}--font-weight: var(--tgs-type-${n}-weight);`,
  );
}
for (const [k, v] of Object.entries(motion.easing)) tw.push(`--ease-${k}: ${v};`);

const tailwindCss = `${HEADER}/* Import AFTER 'tailwindcss' and './tokens.css'. Default Tailwind colours are removed on purpose. */
@theme inline {
${indent(tw, 2)}
}
`;

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'css');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tokens.css'), tokensCss);
writeFileSync(join(outDir, 'tailwind.css'), tailwindCss);
console.log(`design tokens written → ${outDir} (tokens.css, tailwind.css)`);
